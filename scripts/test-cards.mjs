import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:9400';
async function get(path) {
	const response = await fetch(new URL(path, base), { headers: { Cookie: 'playground_auto_login_already_happened=1' }, signal: AbortSignal.timeout(60000) });
	assert.equal(response.status, 200, path);
	return response.text();
}
const home = (await get('/')).replace(/&#x([\da-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)));
assert.match(home, /card-purchase/);
assert.match(home, /card-price-range/);
const range = home.match(/<span class="price card-price-range">([\s\S]+?)<span class="card-price-unit">([^<]+)<\/span>/);
assert.ok(range, 'Range uses one common currency unit');
assert.match(range[1], /300,000/);
assert.match(range[1], /600,000/);
assert.match(range[2], /تومان/);
assert.doesNotMatch(range[1], /تومان/);
const products = JSON.parse(await get('/?rest_route=/wc/store/v1/products&sku=PREVIEW-3'));
assert.equal(products[0].type, 'variable');
const detail = await get(products[0].permalink);
assert.match(detail, /variations_form/);
assert.match(detail, /300000/);
assert.match(detail, /600000/);
assert.match(home, /class="product_type_variable|product_type_variable /);
assert.match(home, /class="card-image"/, 'Product image has an overlay container');
assert.doesNotMatch(home, /class="card-stock">موجود/, 'Available products have no stock badge');
assert.doesNotMatch(home, /class="card-purchase">\s*<span class="card-stock"/, 'Purchase row has no stock/options caption');
assert.match(home, /data-card-variations="\d+"/, 'Variable card offers an accessible lazy picker');
assert.match(home, /data-card-options aria-labelledby="card-options-title"/, 'One native dialog is available');
const formResponse = await fetch(`${base}/wp-admin/admin-ajax.php?action=wpmain_card_variations&product_id=${products[0].id}`, {headers:{Cookie:'playground_auto_login_already_happened=1'},signal:AbortSignal.timeout(90000)});
assert.equal(formResponse.status,200);
const form = await formResponse.json();
assert.equal(form.success,true);
assert.match(form.data.html,/class="variations_form cart"/);
assert.match(form.data.html,/data-product_variations="false"/, 'Variations use native AJAX matching rather than large embedded lists');
const denied = await fetch(`${base}/wp-admin/admin-ajax.php?action=wpmain_card_variations&product_id=bad`, {headers:{Cookie:'playground_auto_login_already_happened=1'},signal:AbortSignal.timeout(90000)});
assert.equal(denied.status,404, 'Malformed product requests cannot expose a form');
console.log('PASS: compact purchase row, single-unit stacked range, native variable-product selection and price data.');
